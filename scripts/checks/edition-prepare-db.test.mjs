// prepare-db merges core schema with edition models and (for a selected edition)
// assembles core + edition migrations under packages/db/prisma/.edition/.
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";

const script = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../editions/prepare-db.mjs",
);

function writeTree(root, tree) {
  for (const [relative, contents] of Object.entries(tree)) {
    const absolute = path.join(root, relative);
    mkdirSync(path.dirname(absolute), { recursive: true });
    writeFileSync(absolute, contents);
  }
}

function fixtureRoot() {
  const root = mkdtempSync(path.join(tmpdir(), "prepare-db-"));
  writeTree(root, {
    "packages/db/prisma/schema.prisma": `generator client {
  provider = "prisma-client"
  output   = "../src/generated/prisma"
}

datasource db {
  provider = "postgresql"
}

model CoreThing {
  id String @id
}
`,
    "packages/db/prisma/migrations/migration_lock.toml": `# Please do not edit this file manually
provider = "postgresql"
`,
    "packages/db/prisma/migrations/20260101000000_core_one/migration.sql":
      '-- CreateTable\nCREATE TABLE "core_one" ("id" TEXT NOT NULL);\n',
    "packages/db/prisma/migrations/20260102000000_core_two/migration.sql":
      '-- CreateTable\nCREATE TABLE "core_two" ("id" TEXT NOT NULL);\n',
    "editions/alpha/db/alpha.prisma": `model AlphaThing {
  id String @id
}
`,
    "editions/zed/db/zed.prisma": `model Zed {
  id String @id
}
`,
    "editions/zed/db/migrations/99990001000000_zed/migration.sql":
      '-- CreateTable\nCREATE TABLE "zed" ("id" TEXT NOT NULL);\n',
  });
  return root;
}

function prepare(root, args = []) {
  return execFileSync(process.execPath, [script, "--root", root, ...args], {
    encoding: "utf8",
  });
}

test("rewrites generator output and appends every edition model", () => {
  const root = fixtureRoot();
  try {
    const out = prepare(root, ["--edition", "default"]);
    assert.match(out, /edition=default/);
    assert.match(out, /models=2/);
    assert.match(out, /migrations=core/);

    const schema = readFileSync(
      path.join(root, "packages/db/prisma/.edition/schema.prisma"),
      "utf8",
    );
    assert.match(schema, /output\s*=\s*"\.\.\/\.\.\/src\/generated\/prisma"/);
    assert.match(schema, /\/\/ from editions\/alpha\/db\/alpha\.prisma/);
    assert.match(schema, /model AlphaThing/);
    assert.match(schema, /\/\/ from editions\/zed\/db\/zed\.prisma/);
    assert.match(schema, /model Zed/);
    assert.ok(
      schema.indexOf("editions/alpha/db/alpha.prisma") <
        schema.indexOf("editions/zed/db/zed.prisma"),
    );
    assert.equal(existsSync(path.join(root, "packages/db/prisma/.edition/migrations")), false);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("selected edition gets core plus edition migrations in sorted order", () => {
  const root = fixtureRoot();
  try {
    const out = prepare(root, ["--edition", "zed"]);
    assert.match(out, /edition=zed/);
    assert.match(out, /migrations=\+1/);

    const migrationsDir = path.join(root, "packages/db/prisma/.edition/migrations");
    assert.equal(existsSync(path.join(migrationsDir, "migration_lock.toml")), true);
    const names = readdirSync(migrationsDir)
      .filter((name) => !name.endsWith(".toml"))
      .sort();
    assert.deepEqual(names, [
      "20260101000000_core_one",
      "20260102000000_core_two",
      "99990001000000_zed",
    ]);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

function prepareFailure(root, args = []) {
  try {
    prepare(root, args);
    return null;
  } catch (error) {
    return String(error.stderr ?? error.message ?? error);
  }
}

test("duplicate model or enum names fail", () => {
  const root = fixtureRoot();
  try {
    writeFileSync(
      path.join(root, "editions/zed/db/clash.prisma"),
      `model CoreThing {\n  id String @id\n}\n`,
    );
    const message = prepareFailure(root, ["--edition", "zed"]);
    assert.match(message ?? "", /Duplicate model or enum "CoreThing"/);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("edition migration that sorts before the last core migration fails", () => {
  const root = fixtureRoot();
  try {
    mkdirSync(path.join(root, "editions/zed/db/migrations/20250101000000_too_early"), {
      recursive: true,
    });
    writeFileSync(
      path.join(root, "editions/zed/db/migrations/20250101000000_too_early/migration.sql"),
      "-- bad\n",
    );
    // Remove the good 9999 migration so only the early one remains.
    rmSync(path.join(root, "editions/zed/db/migrations/99990001000000_zed"), {
      recursive: true,
      force: true,
    });
    const message = prepareFailure(root, ["--edition", "zed"]);
    assert.match(message ?? "", /must sort after the last core migration/);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});
